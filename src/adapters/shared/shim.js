'use strict';
/**
 * Windows launcher shims for hook commands.
 *
 * WHY THIS EXISTS (determined empirically — see scripts/probe-cmd-forms.js):
 * Codex launches a hook by handing its `command` string to %COMSPEC% (cmd.exe).
 * Under `cmd /c "<string>"`, a string that STARTS with a quoted executable path
 * fails outright:
 *
 *     "C:\Program Files\nodejs\node.exe" "E:\ALL PROJECTS\...\hook.js" codex
 *     -> '"C:\Program Files\nodejs\node.exe"' is not recognized as an internal
 *        or external command
 *
 * Codex surfaces that as "hook: PreToolUse Failed", and — critically — a failed
 * hook is non-blocking, so the command would run unapproved. Every quoting
 * variant was tested; the only reliable form is a .cmd launcher referenced as a
 * single bare token containing no spaces. Inside the .cmd, normal quoting works.
 *
 * The shim also pins AGW_HOME, so a hook spawned by an agent always talks to the
 * gateway that installed it rather than whatever the default happens to be.
 */
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const { homeDir } = require('../../core/config');

function hookScriptPath() {
  return path.resolve(__dirname, '..', 'hook.js');
}

function shimDir() {
  return path.join(homeDir(), 'hooks');
}

function shimPath(agentId) {
  const ext = process.platform === 'win32' ? '.cmd' : '.sh';
  return path.join(shimDir(), `${agentId}-hook${ext}`);
}

/**
 * Windows 8.3 short path, which contains no spaces. Returns null when short
 * names are disabled on the volume.
 */
function shortPath(p) {
  if (process.platform !== 'win32') return null;
  try {
    const out = execFileSync(
      process.env.COMSPEC || 'cmd.exe',
      ['/c', `for %I in ("${p}") do @echo %~sI`],
      { encoding: 'utf8', timeout: 10000 }
    ).trim();
    // If the path still has a space, the short name was not generated.
    return out && !out.includes(' ') && fs.existsSync(out) ? out : null;
  } catch {
    return null;
  }
}

/**
 * Write the launcher for one agent and return the token an agent's config
 * should use as its command.
 *
 * @param {'claude'|'codex'|'antigravity'} agentId
 * @returns {{shim: string, command: string, usedShortPath: boolean}}
 */
function writeShim(agentId) {
  const dir = shimDir();
  fs.mkdirSync(dir, { recursive: true });
  const file = shimPath(agentId);
  const node = process.execPath;
  const script = hookScriptPath();
  const home = homeDir();

  const body =
    process.platform === 'win32'
      ? [
          '@echo off',
          'REM Managed by agent-approval-gateway. Regenerated by `agw install-hooks`.',
          'REM Quoting is safe in here; it is not safe in a cmd /c command string.',
          `set "AGW_HOME=${home}"`,
          `"${node}" "${script}" ${agentId} %*`,
          'exit /b %ERRORLEVEL%',
          '',
        ].join('\r\n')
      : [
          '#!/bin/sh',
          '# Managed by agent-approval-gateway. Regenerated by `agw install-hooks`.',
          `AGW_HOME="${home}"`,
          'export AGW_HOME',
          `exec "${node}" "${script}" ${agentId} "$@"`,
          '',
        ].join('\n');

  fs.writeFileSync(file, body);
  if (process.platform !== 'win32') fs.chmodSync(file, 0o755);

  // The command token must contain no spaces, because it is passed through a
  // shell as the first token. Fall back to the 8.3 name when the path has any.
  let command = file;
  let usedShortPath = false;
  if (process.platform === 'win32' && file.includes(' ')) {
    const short = shortPath(file);
    if (short) {
      command = short;
      usedShortPath = true;
    }
  }
  return { shim: file, command, usedShortPath };
}

function removeShim(agentId) {
  const file = shimPath(agentId);
  if (fs.existsSync(file)) {
    fs.unlinkSync(file);
    return true;
  }
  return false;
}

module.exports = { writeShim, removeShim, shimPath, shimDir, hookScriptPath, shortPath };
